using Content.Shared._ClawCommand.Supermatter.Monitor;
using Content.Shared._ClawCommand.Supermatter.Systems;
using Content.Shared.Atmos;
using Content.Shared.DoAfter;
using Content.Shared.Radio;
using Content.Shared.Random;
using Content.Shared.Whitelist;
using Robust.Shared.Audio;
using Robust.Shared.GameStates;
using Robust.Shared.Prototypes;
using Robust.Shared.Serialization;

namespace Content.Shared._ClawCommand.Supermatter.Components;

[RegisterComponent, NetworkedComponent]
public sealed partial class SupermatterComponent : Component
{
    #region SM Base

    /// <summary>
    ///     The SM will only cycle if activated.
    /// </summary>
    [DataField]
    public bool Activated;

    [DataField("supermatterSliverPrototype")]
    public EntProtoId SliverPrototypeId = "SupermatterSliver";

    /// <summary>
    ///     Affects delamination timer. If removed - delamination timer is divided by 2.
    /// </summary>
    [DataField]
    public bool SliverRemoved;

    [DataField]
    public EntityWhitelist Whitelist = new();

    public string IdTag = "EmitterBolt";

    public EntProtoId[] LightningPrototypes =
    {
        "Lightning",
        "ChargedLightning",
        "SuperchargedLightning",
        "HyperchargedLightning",
    };

    [DataField("singularitySpawnPrototype")]
    public EntProtoId SingularityPrototypeId = "Singularity";

    [DataField("teslaSpawnPrototype")]
    public EntProtoId TeslaPrototypeId = "TeslaEnergyBall";

    /// <summary>
    ///     Spawned by a resonance cascade delamination. Cascades are not implemented yet, so this is never used.
    /// </summary>
    [DataField("supermatterKudzuSpawnPrototype")]
    public EntProtoId? SupermatterKudzuPrototypeId;

    [ViewVariables(VVAccess.ReadWrite)]
    public float Power;

    /// <summary>
    ///     Temperature of the last absorbed gas, shown on the monitoring console.
    /// </summary>
    [ViewVariables(VVAccess.ReadWrite)]
    public float Temperature;

    /// <summary>
    ///     Heat modifier of the last absorbed gas, shown on the monitoring console.
    /// </summary>
    [ViewVariables(VVAccess.ReadWrite)]
    public float WasteMultiplier;

    /// <summary>
    ///     The amount of damage we have currently
    /// </summary>
    [ViewVariables(VVAccess.ReadWrite)]
    public float Damage;

    [ViewVariables(VVAccess.ReadWrite)]
    public float MatterPower;

    [ViewVariables(VVAccess.ReadWrite)]
    public float MatterPowerConversion = 10f;

    /// <summary>
    ///     The portion of the gasmix we're on
    /// </summary>
    [ViewVariables(VVAccess.ReadWrite)]
    public float GasEfficiency = 0.15f;

    /// <summary>
    ///     The amount of heat we apply scaled
    /// </summary>
    [ViewVariables(VVAccess.ReadWrite)]
    public float HeatThreshold = 2500f;

    [DataField]
    public float RadiationOutputFactor = 0.03f;

    #endregion SM Base

    #region SM Sound

    /// <summary>
    ///     Current stream of SM audio.
    /// </summary>
    public EntityUid? AudioStream;

    public SharedSupermatterSystem.SuperMatterSound? SmSound;

    [DataField]
    public SoundSpecifier DustSound = new SoundPathSpecifier("/Audio/_ClawCommand/Supermatter/dust.ogg");

    [DataField]
    public SoundSpecifier DelamSound = new SoundPathSpecifier("/Audio/_ClawCommand/Supermatter/delamming.ogg");

    [DataField]
    public SoundSpecifier DelamAlarm = new SoundPathSpecifier("/Audio/Machines/alarm.ogg");

    #endregion SM Sound

    #region SM Calculation

    /// <summary>
    ///     Based on co2 percentage, slowly moves between
    ///     0 and 1. We use it to calc the powerloss_inhibitor
    /// </summary>
    [ViewVariables]
    public float PowerlossDynamicScaling;

    /// <summary>
    ///     Affects the amount of damage and minimum point
    ///     at which the sm takes heat damage
    /// </summary>
    [ViewVariables]
    public float DynamicHeatResistance = 1;

    /// <summary>
    ///     Multiplier on damage the core takes from absorbing hot gas
    ///     Default is ~1/350
    /// </summary>
    [ViewVariables]
    public float MoleHeatPenalty = 0.00286f;

    /// <summary>
    ///     Inverse of MoleHeatPenalty
    /// </summary>
    [ViewVariables]
    public float MoleHeatThreshold = 350f;

    /// <summary>
    ///     Multiplier on power generated by nuclear reactions
    /// </summary>
    [DataField("reactionpowerModifier")]
    public float ReactionPowerModifier = 0.55f;

    /// <summary>
    ///     Acts as a multiplier on the amount that nuclear reactions increase the supermatter core temperature
    /// </summary>
    [DataField("thermalreleaseModifier")]
    public float ThermalReleaseModifier = 0.2f;

    /// <summary>
    ///     Multiplier on how much plasma is released during supermatter reactions
    ///     Default is ~1/750
    /// </summary>
    [DataField("plasmareleaseModifier")]
    public float PlasmaReleaseModifier = 0.001333f;

    /// <summary>
    ///     Multiplier on how much oxygen is released during supermatter reactions.
    ///     Default is ~1/325
    /// </summary>
    [DataField("oxygenreleaseModifier")]
    public float OxygenReleaseEfficiencyModifier = 0.0031f;

    #endregion SM Calculation

    #region SM Timer

    /// <summary>
    ///     The point at which we should start sending messeges
    ///     about the damage to the engi channels.
    /// </summary>
    [DataField("WarningPoint")]
    public float WarningPoint = 50;

    /// <summary>
    ///     The point at which we start sending messages to the common channel
    /// </summary>
    [DataField]
    public float EmergencyPoint = 500;

    /// <summary>
    ///     we yell if over 50 damage every YellTimer Seconds
    /// </summary>
    [ViewVariables(VVAccess.ReadWrite)]
    public float YellTimer = 60f;

    /// <summary>
    ///     set to YellTimer at first so it doesnt yell a minute after being hit
    /// </summary>
    [ViewVariables]
    public float YellAccumulator = 60f;

    /// <summary>
    ///     Timer for delam
    /// </summary>
    [ViewVariables]
    public float DelamTimerAccumulator;

    /// <summary>
    ///     Time until delam
    /// </summary>
    [DataField]
    public float DelamTimer = 120f;

    /// <summary>
    ///     The message timer
    /// </summary>
    [ViewVariables(VVAccess.ReadWrite)]
    public float SpeakAccumulator = 60f;

    [ViewVariables]
    public float UpdateAccumulator;

    [ViewVariables(VVAccess.ReadWrite)]
    public float UpdateTimer = 1f;

    [ViewVariables]
    public float ZapAccumulator;

    [ViewVariables(VVAccess.ReadWrite)]
    public float ZapTimer = 10f;

    #endregion SM Timer

    #region SM Threshold

    /// <summary>
    ///     Higher == Higher percentage of inhibitor gas needed
    ///     before the charge inertia chain reaction effect starts.
    /// </summary>
    [DataField("powerlossinhibitiongasThreshold")]
    public float PowerlossInhibitionGasThreshold = 0.20f;

    /// <summary>
    ///     Higher == More moles of the gas are needed before the charge
    ///     inertia chain reaction effect starts.
    ///     Scales powerloss inhibition down until this amount of moles is reached
    /// </summary>
    [DataField("powerlossinhibitionmoleThreshold")]
    public float PowerlossInhibitionMoleThreshold = 20f;

    /// <summary>
    ///     bonus powerloss inhibition boost if this amount of moles is reached
    /// </summary>
    [DataField("powerlossinhibitionmoleboostThreshold")]
    public float PowerlossInhibitionMoleBoostThreshold = 500f;

    /// <summary>
    ///     Above this value we can get lord singulo and independent mol damage,
    ///     below it we can heal damage
    /// </summary>
    [DataField("molepenaltyThreshold")]
    public float MolePenaltyThreshold = 900f;

    /// <summary>
    ///     more moles of gases are harder to heat than fewer,
    ///     so let's scale heat damage around them
    /// </summary>
    [DataField("moleheatpenaltyThreshold")]
    public float MoleHeatPenaltyThreshold;

    /// <summary>
    ///     The cutoff on power properly doing damage, pulling shit around,
    ///     and delamming into a tesla. Low chance of pyro anomalies, +2 bolts of electricity
    /// </summary>
    [DataField]
    public float PowerPenaltyThreshold = 2500f;

    /// <summary>
    ///     Maximum safe operational temperature in degrees Celsius. Supermatter begins taking damage above this temperature.
    /// </summary>
    [DataField("heatpenaltyThreshold")]
    public float HeatPenaltyThreshold = 40f;

    /// <summary>
    ///     The damage we had before this cycle. Used to limit the damage we can take each cycle, and for safe alert
    /// </summary>
    [ViewVariables(VVAccess.ReadWrite)]
    public float DamageArchived;

    /// <summary>
    ///     is multiplied by ExplosionPoint to cap
    ///     evironmental damage per cycle
    /// </summary>
    [ViewVariables]
    public float DamageHardcap = 0.002f;

    /// <summary>
    ///     environmental damage is scaled by this
    /// </summary>
    [DataField("damageincreaseMultiplier")]
    public float DamageIncreaseMultiplier = 0.25f;

    /// <summary>
    ///     if spaced sm wont take more than 2 damage per cycle
    /// </summary>
    [DataField("maxspaceexposureDamage")]
    public float MaxSpaceExposureDamage = 2;

    #endregion SM Threshold

    #region SM Delamm

    public bool DelamAnnounced;

    /// <summary>
    ///     The point at which we delamm
    /// </summary>
    [DataField("explosionPoint")]
    public int DelaminationPoint = 900;

    /// <summary>
    ///     Are we delamming?
    /// </summary>
    [ViewVariables]
    public bool Delamming;

    /// <summary>
    ///     Explosion totalIntensity value
    /// </summary>
    [DataField]
    public float TotalIntensity = 50000f;

    /// <summary>
    ///     Explosion radius value
    /// </summary>
    [DataField]
    public float Radius = 50f;

    /// <summary>
    ///     These would be what you would get at point blank, decreases with distance
    /// </summary>
    [DataField]
    public float DetonationRads = 200f;

    #endregion SM Delamm

    #region SM Gas

    /// <summary>
    ///     Is used to store gas
    /// </summary>
    [DataField]
    public Dictionary<Gas, float> GasStorage = new()
    {
        { Gas.Oxygen, 0f },
        { Gas.Nitrogen, 0f },
        { Gas.CarbonDioxide, 0f },
        { Gas.Plasma, 0f },
        { Gas.Tritium, 0f },
        { Gas.WaterVapor, 0f },
        { Gas.Ammonia, 0f },
        { Gas.NitrousOxide, 0f },
        { Gas.Frezon, 0f },
    };

    /// <summary>
    ///     Stores each gas facts
    /// </summary>
    public readonly Dictionary<Gas, (float TransmitModifier, float HeatPenalty, float PowerMixRatio, float AngerValue)> GasDataFields = new()
    {
        [Gas.Oxygen] = (TransmitModifier: 1.5f, HeatPenalty: 1f, PowerMixRatio: 1f, AngerValue: 1f),
        [Gas.Nitrogen] = (TransmitModifier: 0f, HeatPenalty: -1.5f, PowerMixRatio: -1f, AngerValue: -1f),
        [Gas.CarbonDioxide] = (TransmitModifier: 0f, HeatPenalty: 0.1f, PowerMixRatio: 1f, AngerValue: 3f),
        [Gas.Plasma] = (TransmitModifier: 4f, HeatPenalty: 15f, PowerMixRatio: 1f, AngerValue: 5f),
        [Gas.Tritium] = (TransmitModifier: 30f, HeatPenalty: 10f, PowerMixRatio: 1f, AngerValue: 10f),
        [Gas.WaterVapor] = (TransmitModifier: 2f, HeatPenalty: 12f, PowerMixRatio: 1f, AngerValue: 3f),
        [Gas.Frezon] = (TransmitModifier: 3f, HeatPenalty: -10f, PowerMixRatio: -1f, AngerValue: -5f),
        [Gas.Ammonia] = (TransmitModifier: 0f, HeatPenalty: .5f, PowerMixRatio: 1f, AngerValue: 1f),
        [Gas.NitrousOxide] = (TransmitModifier: 0f, HeatPenalty: -5f, PowerMixRatio: -1f, AngerValue: -3f),
    };

    #endregion SM Gas

    /// <summary>
    ///     Current alert status, shown on supermatter monitoring consoles.
    /// </summary>
    [DataField]
    public SupermatterStatusType Status = SupermatterStatusType.Inactive;

    #region Events

    [DataField("harsheventThreshold")]
    public float HarshEventThreshold = 5f;

    /// <summary>
    ///     The SM's current anger value, increments to a setpoint then triggers an event
    /// </summary>
    [ViewVariables(VVAccess.ReadWrite)]
    public float SMAngerValue;

    /// <summary>
    ///     The setpoint at which the SM does an event.
    /// </summary>
    [ViewVariables(VVAccess.ReadWrite)]
    public float SMEventSetpoint = 2000f;

    [ViewVariables(VVAccess.ReadWrite)]
    public float SMLastAnger;

    [DataField]
    public ProtoId<WeightedRandomPrototype> HarshEvents = "SupermatterHarshEvents";

    [DataField]
    public ProtoId<WeightedRandomPrototype> NormalEvents = "SupermatterNormalEvents";

    [DataField]
    public ProtoId<RadioChannelPrototype> RadioChannel = "Engineering";

    /// <summary>
    ///     The time in minutes since a surge occurred that variables can be adjusted
    /// </summary>
    [DataField("Timetounlock")]
    public double TimeToUnlock = 5;

    public double TimeLocked;

    /// <summary>
    ///     The desired setpoint for a radiation output factor - bigger number means it will try reach a bigger value
    /// </summary>
    [DataField]
    public float RadiationOutputFactorSetpoint = 0.03f;

    [DataField]
    public bool RadiationOutputFactorChanged;

    /// <summary>
    ///     The desired setpoint for gas efficiency - bigger number means it will try to absorb more gas
    /// </summary>
    [DataField("GasEfficiencySetpoint")]
    public float GasEfficiencySetpoint = 0.15f;

    [DataField("GasEfficiencyFactorChanged")]
    public bool GasEfficiencyFactorChanged;

    [DataField]
    public bool Surge;

    #endregion Events
}

/// <summary>
///     A random event the supermatter runs once its anger value reaches <see cref="SupermatterComponent.SMEventSetpoint"/>.
/// </summary>
[Prototype]
public sealed partial class SupermatterEventPrototype : IPrototype
{
    [IdDataField]
    public string ID { get; private set; } = default!;

    /// <summary>
    ///     Gas released into the supermatter's tile.
    /// </summary>
    [DataField]
    public Gas? GasToSpawn;

    /// <summary>
    ///     Entity spawned next to the supermatter.
    /// </summary>
    [DataField]
    public EntProtoId? ProtoToSpawn;

    /// <summary>
    ///     Starts a surge: absorption and radiation output temporarily double.
    /// </summary>
    [DataField]
    public bool Surge;

    [DataField]
    public LocId? Announcement;
}

